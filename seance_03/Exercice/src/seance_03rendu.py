# Question 5 : Sélectionner les colonnes quantitatives et calculer les paramètres
print("=== Question 5 : Calcul des paramètres statistiques ===")

# Sélectionner les colonnes quantitatives (int et float)
colonnes_quantitatives = []
for col in contenu.columns:
    if contenu[col].dtype in ['int64', 'float64']:
        colonnes_quantitatives.append(col)

print(f"Colonnes quantitatives sélectionnées : {colonnes_quantitatives}")
print("\n")

# Calculer les moyennes avec mean()
moyennes = []
for col in colonnes_quantitatives:
    moy = contenu[col].mean()
    moyennes.append(moy)

for col, moy in zip(colonnes_quantitatives, moyennes):
    print(f"{col} : {moy}")

# Calculer les médianes avec median()
medianes = []
for col in colonnes_quantitatives:
    med = contenu[col].median()
    medianes.append(med)

for col, med in zip(colonnes_quantitatives, medianes):
    print(f"{col} : {med}")

# Calculer les modes avec mode()
modes = []
for col in colonnes_quantitatives:
    mod = contenu[col].mode()
    # mode() retourne une série, on prend la première valeur
    if len(mod) > 0:
        modes.append(mod[0])
    else:
        modes.append(None)

for col, mod in zip(colonnes_quantitatives, modes):
    print(f"{col} : {mod}")

# Calculer l'écart type avec std()
ecarts_types = []
for col in colonnes_quantitatives:
    et = contenu[col].std()
    ecarts_types.append(et)

for col, et in zip(colonnes_quantitatives, ecarts_types):
    print(f"{col} : {et}")

# Calculer l'écart absolu à la moyenne avec abs() de Numpy
ecarts_absolus = []
for col in colonnes_quantitatives:
    moyenne = contenu[col].mean()
    ecart_abs = np.abs(contenu[col] - moyenne).mean()
    ecarts_absolus.append(ecart_abs)

for col, ea in zip(colonnes_quantitatives, ecarts_absolus):
    print(f"{col} : {ea}")

# Calculer l'étendue avec min() et max()
etendues = []
for col in colonnes_quantitatives:
    mini = contenu[col].min()
    maxi = contenu[col].max()
    etendue = maxi - mini
    etendues.append(etendue)

for col, et in zip(colonnes_quantitatives, etendues):
    print(f"{col} : {et}")

# Arrondir tous les paramètres à deux décimales avec round()
moyennes = [round(m, 2) if m is not None else None for m in moyennes]
medianes = [round(m, 2) if m is not None else None for m in medianes]
modes = [round(m, 2) if m is not None else None for m in modes]
ecarts_types = [round(e, 2) if e is not None else None for e in ecarts_types]
ecarts_absolus = [round(e, 2) if e is not None else None for e in ecarts_absolus]
etendues = [round(e, 2) if e is not None else None for e in etendues]

