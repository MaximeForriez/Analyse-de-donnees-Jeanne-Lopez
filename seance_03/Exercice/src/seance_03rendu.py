# Question 7 : Calculer la distance interquartile et interdécile avec quantile()
print("=== Question 7 : Distances interquartile et interdécile ===")

distances_interquartiles = []
distances_interdeciles = []

for col in colonnes_quantitatives:
    # Distance interquartile : Q3 - Q1
    q1 = contenu[col].quantile(0.25)
    q3 = contenu[col].quantile(0.75)
    diq = q3 - q1
    distances_interquartiles.append(round(diq, 2))

    # Distance interdécile : D9 - D1
    d1 = contenu[col].quantile(0.1)
    d9 = contenu[col].quantile(0.9)
    did = d9 - d1
    distances_interdeciles.append(round(did, 2))

print(f"Distances interquartiles : {distances_interquartiles}")
print(f"Distances interdéciles : {distances_interdeciles}")
print("\n")

