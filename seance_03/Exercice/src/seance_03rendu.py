# Question 10 : Catégoriser les îles par surface
print("=== Question 10 : Catégorisation des îles par surface ===")

# Sélectionner la colonne Surface (km²)
surfaces = islands['Surface (km²)']

# Définir les bornes des classes
bornes = [0, 10, 25, 50, 100, 2500, 5000, 10000, float('inf')]
labels = [
    ']0, 10]',
    ']10, 25]',
    ']25, 50]',
    ']50, 100]',
    ']100, 2500]',
    ']2500, 5000]',
    ']5000, 10000]',
    ']10000, +∞['
]

# Algorithme de catégorisation
compteurs = [0] * len(labels)

for surface in surfaces:
    if pd.notna(surface):  # Vérifier que la valeur n'est pas NaN
        if 0 < surface <= 10:
            compteurs[0] += 1
        elif 10 < surface <= 25:
            compteurs[1] += 1
        elif 25 < surface <= 50:
            compteurs[2] += 1
        elif 50 < surface <= 100:
            compteurs[3] += 1
        elif 100 < surface <= 2500:
            compteurs[4] += 1
        elif 2500 < surface <= 5000:
            compteurs[5] += 1
        elif 5000 < surface <= 10000:
            compteurs[6] += 1
        elif surface > 10000:
            compteurs[7] += 1

print("Nombre d'îles par catégorie de surface :")
for i, label in enumerate(labels):
    print(f"{label} km² : {compteurs[i]} îles")
print("\n")

