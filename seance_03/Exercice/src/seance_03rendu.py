print("=== Question 6 : Affichage des paramètres ===")
print(f"Moyennes : {moyennes}")
print(f"Médianes : {medianes}")
print(f"Modes : {modes}")
print(f"Écarts types : {ecarts_types}")
print(f"Écarts absolus à la moyenne : {ecarts_absolus}")
print(f"Étendues : {etendues}")
print("\n")

