#2. Faire des fonctions (informatiques) pour calculer la moyenne et l’écart type des distributions précédentes.

def compute_stats(dist, dist_type='continuous', **params):
    """Calcule la moyenne et l'écart-type d'une distribution."""
    mean, var = dist.stats(**params, moments='mv')
    std = np.sqrt(var)
    return {
        'moyenne': float(mean),
        'ecart_type': float(std),
        'variance': float(var)
    }

