from matplotlib import pyplot as plt

def plot_discrete_distribution(dist, x_range, title, **params):
    """Visualise une distribution discrète."""
    x = np.arange(*x_range)
    pmf = dist.pmf(x, **params)

    plt.figure(figsize=(10, 6))
    plt.bar(x, pmf, alpha=0.7, edgecolor='black')
    plt.title(title, fontsize=14, fontweight='bold')
    plt.xlabel('x', fontsize=12)
    plt.ylabel('Probabilité', fontsize=12)
    plt.grid(alpha=0.3)
    plt.tight_layout()
    plt.show()

# Loi de Dirac (cas particulier : masse en un point)
def plot_dirac(loc=5):
    """Visualise la loi de Dirac."""
    x = np.arange(0, 11)
    y = np.zeros_like(x, dtype=float)
    y[loc] = 1.0

    plt.figure(figsize=(10, 6))
    plt.bar(x, y, alpha=0.7, edgecolor='black')
    plt.title(f'Loi de Dirac (masse en x={loc})', fontsize=14, fontweight='bold')
    plt.xlabel('x', fontsize=12)
    plt.ylabel('Probabilité', fontsize=12)
    plt.grid(alpha=0.3)
    plt.tight_layout()
    plt.show()

# Loi uniforme discrète
def plot_uniform_discrete(low=1, high=10):
    """Visualise la loi uniforme discrète."""
    plot_discrete_distribution(
        stats.randint, (low, high + 1),
        f'Loi uniforme discrète [{low}, {high}]',
        low=low, high=high + 1
    )

# Loi binomiale
def plot_binomial(n=20, p=0.5):
    """Visualise la loi binomiale."""
    plot_discrete_distribution(
        stats.binom, (0, n + 1),
        f'Loi binomiale (n={n}, p={p})',
        n=n, p=p
    )

# Loi de Poisson
def plot_poisson_discrete(mu=5):
    """Visualise la loi de Poisson (variable discrète)."""
    plot_discrete_distribution(
        stats.poisson, (0, mu * 3 + 1),
        f'Loi de Poisson (λ={mu})',
        mu=mu
    )

# Loi de Zipf-Mandelbrot
def plot_zipf(a=2.0, n=20):
    """Visualise la loi de Zipf."""
    plot_discrete_distribution(
        stats.zipf, (1, n + 1),
        f'Loi de Zipf (a={a})',
        a=a
    )

#les distributions statistiques de variables continues suivantes

def plot_continuous_distribution(dist, x_range, title, **params):
    """Visualise une distribution continue."""
    x = np.linspace(*x_range, 500)
    pdf = dist.pdf(x, **params)

    plt.figure(figsize=(10, 6))
    plt.plot(x, pdf, linewidth=2, color='steelblue')
    plt.fill_between(x, pdf, alpha=0.3, color='steelblue')
    plt.title(title, fontsize=14, fontweight='bold')
    plt.xlabel('x', fontsize=12)
    plt.ylabel('Densité de probabilité', fontsize=12)
    plt.grid(alpha=0.3)
    plt.tight_layout()
    plt.show()

# Loi de Poisson (approximation continue)
def plot_poisson_continuous(mu=5):
    """Visualise l'approximation continue de la loi de Poisson."""
    x = np.arange(0, mu * 3 + 1)
    pmf = stats.poisson.pmf(x, mu=mu)

    plt.figure(figsize=(10, 6))
    plt.plot(x, pmf, 'o-', linewidth=2, markersize=6, color='steelblue')
    plt.fill_between(x, pmf, alpha=0.3, color='steelblue')
    plt.title(f'Loi de Poisson continue (λ={mu})', fontsize=14, fontweight='bold')
    plt.xlabel('x', fontsize=12)
    plt.ylabel('Probabilité', fontsize=12)
    plt.grid(alpha=0.3)
    plt.tight_layout()
    plt.show()

# Loi normale
def plot_normal(mu=0, sigma=1):
    """Visualise la loi normale."""
    x_range = (mu - 4*sigma, mu + 4*sigma, 500)
    plot_continuous_distribution(
        stats.norm, x_range,
        f'Loi normale (μ={mu}, σ={sigma})',
        loc=mu, scale=sigma
    )

