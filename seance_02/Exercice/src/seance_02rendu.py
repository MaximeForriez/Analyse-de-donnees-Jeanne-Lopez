# Question 11 : Diagrammes en barres pour inscrits et votant avec matplotlib et boucle
print("=== Question 11 : Diagrammes en barres ===")

# Boucle pour inscrits et votants
colonnes_a_tracer = ['Inscrits', 'Votants']
