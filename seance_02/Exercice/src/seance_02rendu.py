# Question 12 : Diagrammes circulaires avec matplotlib et boucle
print("=== Question 12 : Diagrammes circulaires ===")

for i in range(len(contenu)):
    dept = contenu.iloc[i]['Libellé du département']
    valeurs = [
        contenu.iloc[i]['Blancs'],
        contenu.iloc[i]['Nuls'],
        contenu.iloc[i]['Exprimés'],
        contenu.iloc[i]['Abstentions']
    ]
    labels = ['Blancs', 'Nuls', 'Exprimés', 'Abstentions']

    plt.figure(figsize=(8, 8))
    plt.pie(valeurs, labels=labels, autopct='%1.1f%%')
    plt.title(f'Répartition des votes - {dept}')
    plt.tight_layout()
    nom_fichier = dept.replace(' ', '_').replace('/', '-').replace("'", '')
    plt.savefig(f'./images/repartition_{nom_fichier}.png')
    plt.show()

print(f"{len(contenu)} diagrammes circulaires créés")
print("\n")

