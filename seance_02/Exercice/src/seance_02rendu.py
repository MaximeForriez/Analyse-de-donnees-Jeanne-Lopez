#Question 10 : Calculer les effectifs de chaque colonne avec sum et append
print("=== Question 10 : Effectifs avec sum() et append() ===")
effectifs = []
types_dict = dict(types_colonnes)

for colonne in contenu.columns:
    # Condition : calculer uniquement pour int et float
    if colonne in types_dict:
        if types_dict[colonne] in ['int', 'float']:
            total = contenu[colonne].sum()
            effectifs.append(total)
            print(f"{colonne} : {total}")
    else:
        # Pour les colonnes candidats non listées
        if contenu[colonne].dtype in ['int64', 'float64']:
            total = contenu[colonne].sum()
            effectifs.append(total)
            print(f"{colonne} : {total}")
print("\n")

