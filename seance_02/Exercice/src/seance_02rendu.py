# BONUS : Diagrammes circulaires par candidat
print("=== BONUS : Diagrammes circulaires par candidat ===")

# Identifier les colonnes avec "Voix" (candidats)
colonnes_candidats = [col for col in contenu.columns if 'Voix' in col and '%' not in col]

# Boucle pour chaque département
for i in range(len(contenu)):
    dept = contenu.iloc[i]['Libellé du département']
    valeurs_candidats = []
    labels_candidats = []

    for col in colonnes_candidats:
        valeurs_candidats.append(contenu.iloc[i][col])
        # Extraire le nom du candidat
        nom_candidat = col.split('Voix')[0].strip()
        labels_candidats.append(nom_candidat)

    plt.figure(figsize=(10, 10))
    plt.pie(valeurs_candidats, labels=labels_candidats, autopct='%1.1f%%')
    plt.title(f'Répartition des voix par candidat - {dept}')
    plt.tight_layout()
    nom_fichier = dept.replace(' ', '_').replace('/', '-').replace("'", '')
    plt.savefig(f'./images/candidats_{nom_fichier}.png')
    plt.close()

print(f"{len(contenu)} diagrammes par candidat créés")
print("\n")

